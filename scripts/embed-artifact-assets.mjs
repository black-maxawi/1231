// Precomputes embedded (offline) versions of the demo images and Excel
// workbooks, for the single-file "artifact" build (see vite.artifact.config.ts).
// The normal app keeps fetching these from public/ over HTTP; this script only
// feeds the __ARTIFACT__ code path, which has no network access.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import * as XLSX from 'xlsx';
import { voorraadFotos, personeelFotos } from '../src/data/media.ts';
import { voorraadBestanden, personeelBestanden } from '../src/data/media.ts';

const MAX_ROWS_SHOWN = 1000;

function parseWorkbook(path) {
  const buffer = readFileSync(`public${path}`);
  const wb = XLSX.read(buffer, { type: 'buffer', cellFormula: false, cellHTML: false });
  return wb.SheetNames.map((naam) => {
    const sheet = wb.Sheets[naam];
    const alleRijen = XLSX.utils.sheet_to_json(sheet, { header: 1, blankrows: false, defval: '' });
    const afgekapt = alleRijen.length > MAX_ROWS_SHOWN;
    const rijen = (afgekapt ? alleRijen.slice(0, MAX_ROWS_SHOWN) : alleRijen).map((rij) =>
      rij.map((cel) => (cel instanceof Date ? cel.toLocaleDateString('nl-NL') : String(cel))),
    );
    return { naam, rijen, afgekapt };
  });
}

const alleFotos = [...voorraadFotos, ...personeelFotos];
const images = {};
for (const foto of alleFotos) {
  const bytes = readFileSync(`public${foto.src}`);
  images[foto.src] = `data:image/svg+xml;base64,${bytes.toString('base64')}`;
}

const alleBestanden = [...voorraadBestanden, ...personeelBestanden];
const workbooks = {};
for (const bestand of alleBestanden) {
  workbooks[bestand.bestand] = parseWorkbook(bestand.bestand);
}

mkdirSync('src/data', { recursive: true });

writeFileSync(
  'src/data/embeddedImages.generated.ts',
  `// Generated by scripts/embed-artifact-assets.mjs — do not edit by hand.\nexport const embeddedImages: Record<string, string> = ${JSON.stringify(images, null, 2)};\n`,
);

writeFileSync(
  'src/data/embeddedWorkbooks.generated.ts',
  `// Generated by scripts/embed-artifact-assets.mjs — do not edit by hand.\nimport type { SheetTable } from './embeddedWorkbooksTypes';\nexport const embeddedWorkbooks: Record<string, SheetTable[]> = ${JSON.stringify(workbooks, null, 2)};\n`,
);

writeFileSync(
  'src/data/embeddedWorkbooksTypes.ts',
  `export interface SheetTable {\n  naam: string;\n  rijen: string[][];\n  afgekapt: boolean;\n}\n`,
);

console.log('Embedded artifact-assets gegenereerd:', Object.keys(images).length, 'afbeeldingen,', Object.keys(workbooks).length, 'werkmappen.');
